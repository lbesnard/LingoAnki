#!/usr/bin/env python3
"""
This script automates the creation of language learning materials from personal diary entries.
It processes diary entries written in a primary language, translates them into a study
language, and generates TPRS (Teaching Proficiency Through Reading and Storytelling) lessons.

The script is organized into two main functionalities: Diary Handling and TPRS Creation.

## Core Functionalities:

1.  **Diary Entry Processing (`DiaryHandler`)**:
    *   **Input**: Users can write diary entries in a Markdown file or be prompted
        interactively to provide sentences in their primary language and optionally
        attempt translations into the study language.
    *   **OpenAI Integration**:
        *   Translates primary language sentences to the study language.
        *   Provides grammatical tips and explanations for the translations.
        *   Generates a daily title for diary entries based on their content.
    *   **Output**:
        *   A main Markdown file (e.g., `diary.md`) consolidating all processed diary entries.
        *   Individual daily Markdown files for easier review.
        *   Diary entries written to `diary.json` for spaced-repetition review in the web app.

2.  **TPRS Lesson Generation (`TprsCreation` & `TprsVariantHandler`)**:
    *   **Input**: Uses the processed diary entries (study language sentences).
    *   **OpenAI Integration**: Generates TPRS-style questions and answers (Q&A) for
        each sentence to reinforce comprehension and active recall.
    *   **TPRS Variants**: Creates multiple versions of TPRS content:
        *   **Standard**: Basic Q&A for the translated sentences.
        *   **Enhanced**: Rewrites sentences and Q&A for improved clarity, fluency,
          and naturalness for TTS.
        *   **Future Tense**: Transforms sentences and Q&A into the future tense.
        *   **Present Tense**: Transforms sentences and Q&A into the present tense.
    *   **Output**: For each TPRS variant:
        *   A main Markdown file consolidating all TPRS Q&A for that variant.
        *   Individual daily Markdown files for each variant.
        *   TTS audio lessons (`.mp3`) for each day's TPRS content, allowing for
          listening practice.

## Workflow Summary:

1.  **Configuration**: Script behavior is controlled via a `config.yaml` file (e.g.,
    language settings, OpenAI keys, TTS preferences, output paths).
2.  **Diary Input**: User provides diary entries (manually in Markdown or via prompts).
3.  **Diary Processing**: `DiaryHandler` translates sentences, adds tips, generates titles,

4.  **TPRS Generation**: `TprsCreation` takes the processed diary sentences and, for each
    configured TPRS variant:
    a.  Generates specific Q&A using OpenAI.
    b.  Writes TPRS content to Markdown files.
    c.  Creates TTS audio lessons.

## Diary Entry Template (example for `diary.md`):

# YYYY (Year)

## YYYY/MM/DD: [Optional Title Generated by Script]
- **[Sentence in primary language]**
  <span style="color: #C70039 ">Forsøk</span>: [User's trial translation in study language - optional]
  <span style="color: #097969">Rettelse</span>: [Script-generated translation in study language]
  <span style="color: #dda504">Tips</span>: [Script-generated learning tips]

(Repeat for more sentences)
"""

