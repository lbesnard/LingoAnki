    def _read_variant_tprs_to_dict(self):
        """Reads this variant's TPRS markdown file and parses it into a structured dictionary."""
        path_to_read = self.markdown_script_generated_path
        if not os.path.exists(path_to_read):
            path_to_read = self.markdown_path

        if not os.path.exists(path_to_read):
            self.logging.info(
                f"Markdown file for {self.variant_name} not found at {path_to_read} (or original {self.markdown_path}). Cannot read to dict."
            )
            return {}

        content = self.tprs_creator.read_markdown_file(path_to_read)
        days = re.split(r"^##\s+", content, flags=re.MULTILINE)
        variant_tprs_dict = {}
        for day_block_text in days:
            if day_block_text.strip():
                parsed_day_data, date_str = self.tprs_creator.read_tprs_day_block(
                    day_block_text
                )
                if parsed_day_data and date_str:
                    try:
                        date_obj = datetime.strptime(date_str, "%Y/%m/%d")
                    except ValueError:
                        self.logging.error(
                            f"Invalid date string '{date_str}' in {self.variant_name} TPRS file {path_to_read}. Skipping block."
                        )
                        continue

                    day_output_dict = {}
                    for sentence, qa_list_tuples in parsed_day_data.items():
                        qa_map_for_sentence = {
                            str(i + 1): {"question": q_tuple[0], "answer": q_tuple[1]}
                            for i, q_tuple in enumerate(qa_list_tuples)
                        }
                        day_output_dict[sentence] = qa_map_for_sentence
                    variant_tprs_dict[date_obj] = day_output_dict
        return variant_tprs_dict

    def _read_variant_tprs_from_json(self):
        """Reads this variant's TPRS Q&A data from diary.json into a structured dictionary.

        Returns same format as _read_variant_tprs_to_dict():
            dict: {datetime_obj: {sentence_text: {"1": {"question": ..., "answer": ...}, ...}}}
        """
        json_path = self.tprs_creator.config.get("json_diary_path")
        if not json_path:
            self.logging.warning(
                "json_diary_path not configured; cannot read TPRS from JSON."
            )
            return {}

        _VARIANT_NAME_MAP = {
            "Standard": "original",
            "Enhanced": "enhanced",
            "Future": "future",
            "Present": "present",
        }
        json_key = _VARIANT_NAME_MAP.get(self.variant_name)
        if json_key is None:
            return {}

        from lingodiary.diary_json import load_diary_json

        try:
            diary_json = load_diary_json(json_path)
        except Exception as exc:
            self.logging.error(f"Failed to load diary.json for TPRS read: {exc}")
            return {}

        variant_tprs_dict = {}
        for day in diary_json.diaries:
            if not day.date:
                continue
            try:
                date_obj = datetime.strptime(day.date, "%Y/%m/%d")
            except ValueError:
                continue

            day_output_dict = {}
            for entry in day.entries:
                sentence_text = entry.output_language_translation
                if not sentence_text:
                    continue
                variant_lesson = entry.lessons.get_variant(json_key)
                if not variant_lesson.qa:
                    continue
                qa_map = {
                    str(i + 1): {"question": qa.question, "answer": qa.answer}
                    for i, qa in enumerate(variant_lesson.qa)
                }
                day_output_dict[sentence_text] = qa_map

            if day_output_dict:
                variant_tprs_dict[date_obj] = day_output_dict

        return variant_tprs_dict

    def add_missing_entries(self, diary_dict, base_tprs_dict=None):
        """Adds missing TPRS entries for this variant based on the diary."""
        variant_tprs_content_dict = self._read_variant_tprs_from_json()
        if variant_tprs_content_dict is None:  # Should be {} if file doesn't exist
            variant_tprs_content_dict = {}

        openai_func = self.get_openai_generator()
        updated = False

        if (
            not hasattr(self.tprs_creator, "titles_diary_dict")
            or not self.tprs_creator.titles_diary_dict
        ):
            self.tprs_creator.get_all_diary_titles()

        for diary_date, date_entry in diary_dict.items():
            # Ensure diary_date is a datetime object for comparison and dictionary key
            if isinstance(diary_date, str):
                try:
                    # Ensure conversion to datetime.datetime if it's a string
                    diary_date = datetime.strptime(diary_date, "%Y-%m-%d")
                except ValueError:
                    try:
                        diary_date = datetime.strptime(diary_date, "%Y/%m/%d")
                    except ValueError:
                        self.logging.error(
                            f"Invalid date format '{diary_date}' from diary_dict. Skipping."
                        )
                        continue

            # diary_date is datetime.datetime (from diary_dict or parsed string)
            # variant_tprs_content_dict and base_tprs_dict are keyed by datetime.datetime.
            # So, use diary_date directly as diary_date_key.
            diary_date_key = diary_date

            # Ensure the date entry exists in the variant's content dictionary
            if diary_date_key not in variant_tprs_content_dict:
                variant_tprs_content_dict[diary_date_key] = {}
                # updated = True # Adding a new date means we will likely update

            current_day_variant_content = variant_tprs_content_dict[diary_date_key]

            for sentence_no, sentence_details in date_entry.get(
                "sentences", {}
            ).items():
                diary_sentence_text = sentence_details.get("study_language_sentence")
                if not diary_sentence_text:
                    continue

                # Determine if this sentence needs processing for this variant
                needs_processing = False
                if self.variant_name == "Standard":
                    if diary_sentence_text not in current_day_variant_content:
                        needs_processing = True
                else:  # For 'Enhanced', 'Future', 'Present'
                    # Check at the sentence level: a sentence is missing if the base
                    # Standard TPRS sentence is not yet present in this variant's content
                    # for this date. This handles both brand-new dates AND new sentences
                    # added to an existing date.
                    if diary_sentence_text not in current_day_variant_content:
                        needs_processing = True

                if needs_processing:
                    self.logging.info(
                        f"Missing/New {self.variant_name} TPRS for '{diary_sentence_text}' on {diary_date_key}. Generating."
                    )
                    updated = True
                    # Track this date for per-date audio regeneration
                    date_str_for_regen = (
                        diary_date_key.strftime("%Y/%m/%d")
                        if hasattr(diary_date_key, "strftime")
                        else diary_date_key
                    )
                    self.tprs_creator._dates_to_regenerate.add(date_str_for_regen)

                    try:
                        if self.needs_base_tprs_data:
                            if (
                                not base_tprs_dict
                                or diary_date_key not in base_tprs_dict
                                or diary_sentence_text
                                not in base_tprs_dict.get(diary_date_key, {})
                            ):
                                self.logging.warning(
                                    f"Missing base TPRS data for {self.variant_name} variant, sentence: '{diary_sentence_text}' on {diary_date_key} during add_missing. Skipping."
                                )
                                continue
                            existing_qa_for_sentence = base_tprs_dict[diary_date_key][
                                diary_sentence_text
                            ]
                            qa_block = openai_func(
                                diary_sentence_text, existing_qa_for_sentence
                            )
                            current_day_variant_content.update(qa_block)
                        else:  # Standard TPRS
                            qa_data = openai_func(diary_sentence_text)
                            current_day_variant_content[diary_sentence_text] = qa_data
                    except Exception as e:
                        self.logging.error(
                            f"Error generating {self.variant_name} TPRS for sentence '{diary_sentence_text}' during add_missing: {e}",
                            exc_info=True,
                        )
                        continue  # Skip this sentence

        # breakpoint()
        # if updated:
        #     self.logging.info(
        #         f"Updating {self.variant_name} TPRS markdown file with missing/new entries: {self.markdown_script_generated_path}"
        #     )
        sorted_tprs_variant_dict = dict(sorted(variant_tprs_content_dict.items()))
        self.write_json_tprs(sorted_tprs_variant_dict)
        # else:
        #     self.logging.info(
        #         f"No missing/new entries found or generated for {self.variant_name} TPRS based on diary."
        #     )


